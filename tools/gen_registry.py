#!/usr/bin/env python3
"""List generated games for linking: writes <gen>/registry.c with one nrt_game_entry per slug.

    python tools/gen_registry.py [--gen DIR] slug [slug ...]      (a slug is a folder written by gen_insn.py)
"""
import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gen", default=os.path.join(ROOT, "generated"))
    ap.add_argument("--file", default="registry.c", help="output file name inside --gen")
    ap.add_argument("slugs", nargs="*", help="default: every generated game under --gen")
    a = ap.parse_args()
    slugs = a.slugs or sorted(d for d in os.listdir(a.gen) if os.path.exists(os.path.join(a.gen, d, "codegen_report.json")))
    if not slugs:
        sys.exit("no generated games found")
    entries = []
    for slug in slugs:
        rep = json.load(open(os.path.join(a.gen, slug, "codegen_report.json")))
        entries.append((slug, rep["symbol"]))
    out = ["/* Generated by gen_registry.py. Do not edit. */\n#include \"nrt.h\"\n\n"]
    for _, sym in entries:
        out.append("extern const nrt_cart %s_cart;\nextern const nrt_code_module %s_module;\n" % (sym, sym))
    out.append("\nconst nrt_game_entry nrt_game_registry[] = {\n")
    for slug, sym in entries:
        out.append("\t{ \"%s\", &%s_cart, &%s_module },\n" % (slug, sym, sym))
    out.append("};\nconst unsigned nrt_game_registry_count = %d;\n" % len(entries))
    open(os.path.join(a.gen, a.file), "w", newline="\n").write("".join(out))
    print("%s: %d games" % (a.file, len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
