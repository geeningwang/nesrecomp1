#!/usr/bin/env python3
"""Generates tools/opcodes.py (the 256-entry 6502 decode table) from nes1's parity-verified CPU table.

    python tools/gen_opcodes.py [path/to/nes1/src/cpu.cpp]

One table, one source of truth: the same instruction/size/cycle data that nes1 proved identical to FCEUX
(all 256 opcodes incl. the undocumented ones) is reused here, so the recompiler cannot disagree with it.
Entry: (mnemonic, mode, size, cycles, page_cross_extra); KIL has size 0 (it never advances the PC).
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "deps", "nes1", "src", "cpu.cpp")
text = open(src, encoding="utf-8", errors="replace").read()

ids = {}
for name, val in re.findall(r"^#define\s+([A-Z]+)\s+(\d+)\s*$", text, re.M):
    ids[name] = int(val)
modes = dict(re.findall(r"^#define\s+(ADDR_[A-Z_]+)\s+(\d+)", text, re.M))
modes = {k: int(v) for k, v in modes.items()}

block = re.search(r"instruction_name\[\]\[5\]\s*=\s*\{(.*?)\};", text, re.S).group(1)
names = [n.strip() for n in re.findall(r"\"([^\"]*)\"", block)]

# instruction id -> mnemonic (the S-prefixed defines are the undocumented ones)
id_to_name = {}
for k, v in ids.items():
    if v < len(names) and not k.startswith("ADDR_"):
        id_to_name.setdefault(v, names[v])

tbl = re.search(r"opcode opcode_items\[\]\s*=\s*\{(.*?)\n\};", text, re.S).group(1)
items = re.findall(r"\{\s*(\w+)\s*,\s*(\d+)\s*,\s*(\w+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", tbl)
assert len(items) == 256, len(items)

mode_name = {v: k[5:].lower() for k, v in modes.items()}
out = ["# GENERATED by tools/gen_opcodes.py from nes1 src/cpu.cpp - do not edit.",
       "# (mnemonic, addressing mode, size, base cycles, extra cycle on page cross / branch taken)",
       "OPCODES = ["]
for i, (ins, size, mode, cyc, extra) in enumerate(items):
    out.append("    (%r, %r, %d, %d, %d),  # %02X" % (id_to_name[ids[ins]].strip(), mode_name[modes[mode]], int(size), int(cyc), int(extra), i))
out.append("]")
open(os.path.join(HERE, "opcodes.py"), "w").write("\n".join(out) + "\n")
print("wrote tools/opcodes.py")
